// Voice pipeline helper.
//   node tools/voice-script.mjs           -> writes assets/voice/SCRIPT.md + script.csv (what to record)
//                                            and assets/voice/manifest.json (which clips exist)
// Record each line as assets/voice/<voice>/<id>.mp3 (or .m4a / .ogg / .wav), then run this again
// so the game picks the clips up. Anything not recorded keeps using text-to-speech.
import { readFileSync, writeFileSync, readdirSync, existsSync, mkdirSync } from 'fs';
import { join, dirname, extname, basename } from 'path';
import { fileURLToPath } from 'url';
import { BARKS, VOICES, CHARACTER_VOICES, CIV_VOICES, lineIdFor } from '../src/data/barks.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'assets/voice');
mkdirSync(out, { recursive: true });
const AUDIO = ['.mp3', '.m4a', '.ogg', '.opus', '.wav', '.webm'];

// 1. street barks: every line for every voice allowed to say it
const rows = [];
const hashV = (s) => { let h = 2166136261; for (let i = 0; i < s.length; i++) h = Math.imul(h ^ s.charCodeAt(i), 16777619); return h >>> 0; };
for (const [cat, B] of Object.entries(BARKS)) {
  for (const [id, text, gloss, only] of B.lines) {
    const vs = only || B.voices;
    // first pass: one woman and one man per line (the game borrows a same-gender recording for the others)
    const first = new Set();
    for (const fem of [true, false]) {
      const g = vs.filter((v) => !!VOICES[v].female === fem);
      if (g.length) first.add(g[hashV(id) % g.length]);
    }
    for (const v of vs) rows.push({ voice: v, id, cat, text, gloss: gloss || '', first: first.has(v) });
  }
}

// 2. scripted mission barks with fixed text: bark(api, 'Who', 'text') and hud.say('Who', pick([...]))
const voiceFor = (who, text) => CHARACTER_VOICES[who] || CIV_VOICES[hashV(text) % CIV_VOICES.length];
const scripted = new Map();
for (const f of ['src/missions/story.js', 'src/missions/sideQuests.js', 'src/missions/activities.js']) {
  const src = readFileSync(join(root, f), 'utf8');
  const add = (who, text) => scripted.set(text, { voice: voiceFor(who, text), id: lineIdFor(text), cat: 'mission', text, gloss: '', who, file: f, first: true });
  for (const m of src.matchAll(/bark\(api,\s*(['"])(.+?)\1,\s*(['"`])((?:\\.|(?!\3).)*)\3/g)) {
    if (m[3] !== '`') add(m[2], m[4].replace(/\\(.)/g, '$1'));
  }
  for (const m of src.matchAll(/hud\.say\((['"])(.+?)\1,\s*pick\((\[[^\]]*\])\)/g)) {
    try {
      for (const t of Function(`return ${m[3]}`)()) add(m[2], t);
    } catch {
      /* contains variables (e.g. a destination name): left to text-to-speech */
    }
  }
}
rows.push(...scripted.values());

// 3. manifest of recorded clips
const manifest = { voices: {} };
let have = 0;
for (const v of Object.keys(VOICES)) {
  const dir = join(out, v);
  if (!existsSync(dir)) continue;
  for (const f of readdirSync(dir)) {
    const ext = extname(f).toLowerCase();
    if (!AUDIO.includes(ext)) continue;
    (manifest.voices[v] ||= {})[basename(f, ext)] = ext.slice(1);
    have++;
  }
}
writeFileSync(join(out, 'manifest.json'), JSON.stringify(manifest, null, 1) + '\n');

// 4. the script
const esc = (s) => String(s).replace(/\|/g, '\\|');
const csvq = (s) => `"${String(s).replace(/"/g, '""')}"`;
writeFileSync(join(out, 'script.csv'), 'voice,file,first_pass,category,line,english\n' + rows.map((r) => [r.voice, `${r.voice}/${r.id}.mp3`, r.first ? 'yes' : '', r.cat, csvq(r.text), csvq(r.gloss)].join(',')).join('\n') + '\n');
let md = `# Mother City — voice recording script\n\nGenerated by \`node tools/voice-script.mjs\` from \`src/data/barks.js\`. Don't edit by hand.\n\n` +
  `**${rows.length} clips** across ${Object.keys(VOICES).length} voices · ${have} recorded so far.\n` +
  `**First pass: the ${rows.filter((r) => r.first).length} lines marked ★** — one woman's and one man's take of every line; ` +
  `other voices borrow those until their own takes exist.\n\n` +
  `How to record: one line per file, 0.2 s of silence either side, no music, mono, 44.1 or 48 kHz. Say it like you would on the street — ` +
  `short, natural, a bit loud. Do 2–3 takes of the important ones and keep the best. Save as \`assets/voice/<voice>/<id>.mp3\` ` +
  `(file names below), then run \`node tools/voice-script.mjs\` again. Every speaker signs a release allowing use in the game.\n\n` +
  `Lines in Afrikaans, Kaaps or isiXhosa show the English meaning in brackets — please fix anything that sounds wrong to a native speaker.\n`;
for (const [v, prof] of Object.entries(VOICES)) {
  const mine = rows.filter((r) => r.voice === v).sort((a, b) => b.first - a.first);
  if (!mine.length) continue;
  md += `\n## ${prof.label} — \`${v}\` (${mine.length} lines)\n\n| File | Situation | Line |\n|---|---|---|\n`;
  for (const r of mine) {
    const done = manifest.voices[v] && manifest.voices[v][r.id] ? ' ✅' : '';
    md += `| ${r.first ? '★ ' : ''}\`${r.id}\`${done} | ${r.cat}${r.who ? ` (${esc(r.who)})` : ''} | ${esc(r.text)}${r.gloss ? ` *(${esc(r.gloss)})*` : ''} |\n`;
  }
}
writeFileSync(join(out, 'SCRIPT.md'), md);
console.log(`${rows.filter((r) => r.first).length} first-pass clips, ${rows.length} total`);
console.log(`${rows.length} clips to record (${scripted.size} scripted mission lines), ${have} recorded. Wrote assets/voice/SCRIPT.md, script.csv, manifest.json`);
